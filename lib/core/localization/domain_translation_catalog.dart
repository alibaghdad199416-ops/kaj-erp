  static String translate(String value, String languageCode) {
    final trimmed = value.trim();
    if (trimmed.isEmpty) return value;
    String? canonical = _aliases[trimmed];
    if (canonical == null) {
      for (final entry in _values.entries) {
        final matches = entry.value.values.any(
          (candidate) => candidate.toLowerCase() == trimmed.toLowerCase(),
        );
        if (matches) {
          canonical = entry.key;
          break;
        }
      }
    }
    canonical ??= _canonicalKey(trimmed);
    final translated = _values[canonical]?[languageCode];
    return translated ?? value;
  }

  static String _canonicalKey(String value) => value
      .replaceAllMapped(
        RegExp(r'([a-z0-9])([A-Z])'),
        (match) => '${match.group(1)}_${match.group(2)}',
      )
      .trim()
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9\u0600-\u06ff]+'), '_')
      .replaceAll(RegExp(r'_+'), '_')
      .replaceAll(RegExp(r'^_|_$'), '');

  static String repairMojibake(String value) {
    if (!value.contains('\u00C3') &&
        !value.contains('\u00C2') &&
        !value.contains('\u00E2')) {
      return value;
